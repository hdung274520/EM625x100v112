VK_PAUSE, VK_NUMLOCK = 0x13, 0x90


def hid_from_win_scancode(scancode: int, vk: int = 0) -> int | None:
    """Windows scan code (+ virtual key to tell Pause from Num Lock) -> HID usage."""
    if vk == VK_PAUSE:
        return 0x48
    if vk == VK_NUMLOCK:
        return 0x53
    if scancode in WIN_EXTENDED_TO_HID:
        return WIN_EXTENDED_TO_HID[scancode]
    return EVDEV_TO_HID.get(scancode) if scancode <= 0x58 else None


def key_name(usage: int) -> str:
    return HID_NAMES.get(usage, f"0x{usage:02X}")


def combo_name(mods: int, usage: int) -> str:
    parts = []
    for bit, name in ((0x01, "Ctrl"), (0x02, "Shift"), (0x04, "Alt"), (0x08, "Win")):
        if mods & (bit | bit << 4):
            parts.append(name)
    if usage:
        parts.append(key_name(usage))
    return "+".join(parts) if parts else "—"
